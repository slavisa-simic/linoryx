-- A counter is kept after a node is deleted. This is not a city catalog.
CREATE TABLE IF NOT EXISTS node_code_counters (
    prefix VARCHAR(180) PRIMARY KEY,
    last_number BIGINT NOT NULL CHECK (last_number > 0)
);

-- Preserve historical incidents and their original status, creator, assignment and resolution date.
-- Hibernate adds the legacy column with DEFAULT true; new Incident constructors write false.
ALTER TABLE incidents DROP CONSTRAINT IF EXISTS incidents_status_check;
UPDATE incidents SET legacy_status = status WHERE legacy = true AND legacy_status IS NULL;
UPDATE incidents SET status = 'IN_PROGRESS' WHERE status = 'RESOLVED';
ALTER TABLE incidents ADD CONSTRAINT incidents_status_check CHECK (status IN ('OPEN', 'IN_PROGRESS', 'CLOSED'));

-- Additive, idempotent VIGIL 2.0 migration. Never replace existing profile information.
CREATE TABLE IF NOT EXISTS technician_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
    latitude NUMERIC(10,7),
    longitude NUMERIC(10,7),
    availability VARCHAR(30),
    location_updated_at TIMESTAMP
);
CREATE TABLE IF NOT EXISTS technician_specializations (
    profile_id BIGINT NOT NULL REFERENCES technician_profiles(id),
    specialization VARCHAR(30) NOT NULL,
    UNIQUE (profile_id, specialization)
);
ALTER TABLE technician_profiles DROP CONSTRAINT IF EXISTS technician_coordinates_check;
ALTER TABLE technician_profiles ADD CONSTRAINT technician_coordinates_check CHECK (
    (latitude IS NULL AND longitude IS NULL AND location_updated_at IS NULL)
    OR (latitude IS NOT NULL AND longitude IS NOT NULL
        AND latitude BETWEEN -90 AND 90 AND longitude BETWEEN -180 AND 180)
);
ALTER TABLE technician_profiles DROP CONSTRAINT IF EXISTS technician_availability_check;
ALTER TABLE technician_profiles ADD CONSTRAINT technician_availability_check
    CHECK (availability IN ('AVAILABLE', 'BUSY', 'OFF_DUTY'));
ALTER TABLE technician_specializations DROP CONSTRAINT IF EXISTS technician_specialization_check;
ALTER TABLE technician_specializations ADD CONSTRAINT technician_specialization_check
    CHECK (specialization IN ('FIBER', 'GPON', 'ROUTING', 'WIRELESS', 'DSL'));
